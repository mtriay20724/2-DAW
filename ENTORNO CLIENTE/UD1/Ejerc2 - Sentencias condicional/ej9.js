let fruta = "manzana";

switch(fruta){
    case "manzana":
        console.log("Es una manzana roja");
        break;
    case "platano":
        console.log("Es un platano amarillo");
        break;
    case "uva":
        console.log("Es una uva morada");
        break;
    default:
        console.log("Fruta no reconocida");
        break;
}